CREATE SEQUENCE HIBERNATE_SEQUENCE START WITH 1 INCREMENT BY 1;
CREATE TABLE POV_FOLDER
   (	ID NUMBER(20) AUTO_INCREMENT,
	NAME VARCHAR2(250) UNIQUE NOT NULL,
	INSERT_DATE DATE NOT NULL,
	PRIMARY KEY (ID)
   );

CREATE TABLE POV_IMAGE
   (	ID NUMBER AUTO_INCREMENT,
	IMAGE BLOB,
	PRIMARY KEY (ID)
   );

CREATE TABLE POV_IMAGE_DETAILS
   (	ID NUMBER AUTO_INCREMENT,
	INSERT_DATE DATE,
	QUALITY VARCHAR2(250),
	DESCRIPTION VARCHAR2(250),
	IMAGE_NAME VARCHAR2(250),
	FOLDER_FOLDERID NUMBER DEFAULT NULL,
	IMAGE_IMAGEID NUMBER,
	THUMBNAIL_IMAGEID NUMBER,
	MODAL_IMAGEID NUMBER,
	PRIMARY KEY (ID)
   );
CREATE TABLE POV_TAG
   (	ID NUMBER AUTO_INCREMENT,
	NAME VARCHAR2(250),
	IMAGE_DETAILS NUMBER
   )
